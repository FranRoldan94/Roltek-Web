import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import type { ComponentType } from "react";
import { cacheLife } from "next/cache";
import GithubSlugger from "github-slugger";
import type { Locale } from "@/i18n/config";
import type { Post, PostMetadata } from "@/types/content";

const BLOG_DIR = path.join(process.cwd(), "src/content/blog");
const WORDS_PER_MINUTE = 220;

const showDrafts = process.env.NODE_ENV === "development";

/** Articles live in `src/content/blog/<slug>/<locale>.mdx`. */
async function readSource(slug: string, locale: Locale) {
  try {
    return await readFile(path.join(BLOG_DIR, slug, `${locale}.mdx`), "utf8");
  } catch {
    return undefined;
  }
}

function stripCode(source: string) {
  return source.replace(/```[\s\S]*?```/g, "");
}

function readingTime(source: string) {
  const words = stripCode(source)
    .replace(/^export const metadata[\s\S]*?\n};?\n/m, "")
    .split(/\s+/)
    .filter(Boolean).length;
  return Math.max(1, Math.round(words / WORDS_PER_MINUTE));
}

/** Mirrors the ids generated by rehype-slug so TOC links resolve. */
function extractHeadings(source: string): Post["headings"] {
  const slugger = new GithubSlugger();
  return [...stripCode(source).matchAll(/^(#{2,3})\s+(.+)$/gm)].map(
    ([, hashes, raw]) => {
      const text = raw.replace(/[`*_]/g, "").trim();
      return {
        id: slugger.slug(text),
        text,
        level: hashes.length as 2 | 3,
      };
    },
  );
}

async function loadMetadata(slug: string, locale: Locale) {
  const mod = (await import(`@/content/blog/${slug}/${locale}.mdx`)) as {
    metadata: PostMetadata;
  };
  return mod.metadata;
}

export async function getPosts(locale: Locale): Promise<Post[]> {
  "use cache";
  cacheLife("max");

  const entries = await readdir(BLOG_DIR, { withFileTypes: true }).catch(
    () => [],
  );
  const posts = await Promise.all(
    entries
      .filter((entry) => entry.isDirectory())
      .map(async ({ name: slug }) => {
        const source = await readSource(slug, locale);
        if (!source) return undefined;
        const metadata = await loadMetadata(slug, locale);
        return {
          ...metadata,
          slug,
          locale,
          readingTime: readingTime(source),
          headings: extractHeadings(source),
        } satisfies Post;
      }),
  );

  return posts
    .filter((post): post is Post => !!post && (showDrafts || !post.draft))
    .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
}

export async function getPost(slug: string, locale: Locale) {
  const posts = await getPosts(locale);
  return posts.find((post) => post.slug === slug);
}

export async function getPostContent(slug: string, locale: Locale) {
  const mod = (await import(`@/content/blog/${slug}/${locale}.mdx`)) as {
    default: ComponentType;
  };
  return mod.default;
}
